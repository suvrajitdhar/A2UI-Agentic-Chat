package com.sdz.smpl.a2ui.ui.chat

import androidx.a2ui.model.processor.A2uiSurfaceModel
import androidx.compose.runtime.Immutable
import androidx.compose.runtime.Stable
import com.sdz.smpl.a2ui.domain.model.AgentMode

/**
 * MVI contract of the chat screen.
 *
 * - [ChatUiState]: everything the screen renders.
 * - [ChatIntent]: everything the user can do (outside the agent's own UI).
 * - [ChatEffect]: one-off events for the UI.
 *
 * Interactions *inside* agent surfaces (button taps, form edits) are handled by the A2UI renderer
 * itself and reach the agent without going through [ChatIntent].
 */
@Immutable
data class ChatUiState(
    val mode: AgentMode = AgentMode.Default,
    val items: List<ChatItem> = emptyList(),
    val input: String = "",
    val isAgentWorking: Boolean = false,
    val statusText: String? = null,
) {
    /** Whether the send button is enabled. */
    val canSend: Boolean get() = input.isNotBlank() && !isAgentWorking

    /** Whether to show the empty state with suggestions. */
    val showSuggestions: Boolean get() = items.isEmpty() && !isAgentWorking
}

/** One row of the conversation list. */
@Immutable
sealed interface ChatItem {
    /** Stable, unique key for the lazy list. */
    val key: String

    data class UserMessage(override val key: String, val text: String) : ChatItem
    data class AgentMessage(override val key: String, val text: String) : ChatItem
    data class ErrorMessage(override val key: String, val text: String) : ChatItem

    /**
     * Native UI generated by the agent.
     *
     * @property surface the live surface model. It is backed by Compose snapshot state, so its
     *   content updates without this item changing.
     */
    @Stable
    data class AgentSurface(override val key: String, val surface: A2uiSurfaceModel) : ChatItem
}

/** User intents on the chat screen. */
sealed interface ChatIntent {
    /** The text in the input field changed. */
    data class InputChanged(val text: String) : ChatIntent

    /** Send the current input. */
    data object SendInput : ChatIntent

    /** Send a suggested prompt directly. */
    data class SendSuggestion(val text: String) : ChatIntent

    /** Change the agent mode; it applies from the next request. */
    data class SelectMode(val mode: AgentMode) : ChatIntent

    /** Clear the conversation and start a new server session. */
    data object StartNewConversation : ChatIntent
}

/** One-off events emitted by the chat screen's ViewModel. */
sealed interface ChatEffect {
    /** The agent mode was changed; confirm it to the user. */
    data class ModeChanged(val mode: AgentMode) : ChatEffect
}
