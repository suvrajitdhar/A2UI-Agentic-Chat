/** A message the user sent: right-aligned, primary color. */
@Composable
fun UserBubble(text: String, modifier: Modifier = Modifier) {
    Bubble(
        text = text,
        alignment = Alignment.CenterEnd,
        container = MaterialTheme.colorScheme.primary,
        content = MaterialTheme.colorScheme.onPrimary,
        shape = RoundedCornerShape(20.dp, 20.dp, 4.dp, 20.dp),
        modifier = modifier,
    )
}

/** A chat message from the agent: left-aligned, neutral color. */
@Composable
fun AgentBubble(text: String, modifier: Modifier = Modifier) {
    Bubble(
        text = text,
        alignment = Alignment.CenterStart,
        container = MaterialTheme.colorScheme.surfaceContainerHigh,
        content = MaterialTheme.colorScheme.onSurface,
        shape = RoundedCornerShape(20.dp, 20.dp, 20.dp, 4.dp),
        modifier = modifier,
    )
}

/** A failed turn: left-aligned, error color. */
@Composable
fun ErrorBubble(text: String, modifier: Modifier = Modifier) {
    Bubble(
        text = text,
        alignment = Alignment.CenterStart,
        container = MaterialTheme.colorScheme.errorContainer,
        content = MaterialTheme.colorScheme.onErrorContainer,
        shape = RoundedCornerShape(12.dp),
        modifier = modifier,
    )
}

/**
 * Native UI generated by the agent, rendered by the A2UI Material 3 catalog.
 *
 * Why the height bound: the catalog's `List` component is a `LazyColumn`, which throws if it is
 * measured with *infinite* height, as happens inside the chat's own `LazyColumn`. Any finite bound
 * avoids that, and a lazy list with a finite bound simply wraps its content. So [maxHeight] is
 * deliberately large: it must never clip a normal surface (a small bound would cut off forms).
 *
 * @param surface the live surface model from the renderer.
 * @param maxHeight finite upper bound for the surface; only reached by extremely long surfaces.
 */
@Composable
fun AgentSurfaceCard(
    surface: A2uiSurfaceModel,
    modifier: Modifier = Modifier,
    maxHeight: Dp = 4_000.dp,
) {
    Box(
        modifier = modifier
            .fillMaxWidth()
            .heightIn(max = maxHeight),
    ) {
        A2uiSurface(surfaceModel = surface, modifier = Modifier.fillMaxWidth())
    }
}

@Composable
private fun Bubble(
    text: String,
    alignment: Alignment,
    container: Color,
    content: Color,
    shape: RoundedCornerShape,
    modifier: Modifier = Modifier,
) {
    Box(modifier = modifier.fillMaxWidth(), contentAlignment = alignment) {
        Surface(
            color = container,
            contentColor = content,
            shape = shape,
            modifier = Modifier.widthIn(max = 300.dp),
        ) {
            Text(
                text = text,
                style = MaterialTheme.typography.bodyLarge,
                modifier = Modifier.padding(horizontal = 14.dp, vertical = 10.dp),
            )
        }
    }
}

